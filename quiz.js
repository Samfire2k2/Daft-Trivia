export class QuizGame {
  constructor(userId, questionCount = 10, language = 'fr') {
    this.userId = userId;
    this.language = language;
    this.questionCount = questionCount;
    this.selectedQuestions = this.selectRandomQuestions(questionCount);
    this.currentQuestion = 0;
    this.score = 0;
    this.answers = [];
    this.completed = false;
    this.isDaily = false;
  }

  selectRandomQuestions(count) {
    const shuffled = [...QUIZ_QUESTIONS].sort(() => Math.random() - 0.5);
    return shuffled.slice(0, Math.min(count, QUIZ_QUESTIONS.length));
  }

  getCurrentQuestion() {
    if (this.currentQuestion < this.selectedQuestions.length) {
      const q = this.selectedQuestions[this.currentQuestion];
      return this.language === 'en' ? q.en : q.fr;
    }
    return null;
  }

  answerQuestion(answer) {
    const current = this.selectedQuestions[this.currentQuestion];
    if (!current) return false;
    const isCorrect = answer === current.correct;
    if (isCorrect) this.score += 10;
    this.answers.push({ questionId: current.id, answer, correct: isCorrect });
    this.currentQuestion++;
    if (this.currentQuestion >= this.selectedQuestions.length) this.completed = true;
    return isCorrect;
  }

  getResults() {
    return {
      totalQuestions: this.selectedQuestions.length,
      correctAnswers: this.answers.filter(a => a.correct).length,
      score: this.score,
      percentage: Math.round((this.answers.filter(a => a.correct).length / this.selectedQuestions.length) * 100)
    };
  }

  getScoreEmbed() {
    const results = this.getResults();
    const maxScore = this.selectedQuestions.length * 10;
    const medal = results.percentage === 100 ? '🏆' : results.percentage >= 75 ? '🥇' : results.percentage >= 50 ? '🥈' : '🥉';
    return {
      title: this.language === 'en' ? `${medal} Daft Punk Quiz - Results` : `${medal} Quiz Daft Punk - Résultats`,
      description: this.language === 'en' ? `Final Score: **${results.score}/${maxScore}**` : `Score final: **${results.score}/${maxScore}**`,
      fields: [{name: this.language === 'en' ? 'Correct Answers' : 'Bonnes réponses', value: `${results.correctAnswers}/${results.totalQuestions}`, inline: true}, {name: this.language === 'en' ? 'Percentage' : 'Pourcentage', value: `${results.percentage}%`, inline: true}],
      color: results.percentage === 100 ? 65280 : results.percentage >= 75 ? 43520 : results.percentage >= 50 ? 16776960 : 16711680
    };
  }
}
